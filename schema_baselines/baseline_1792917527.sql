CREATE OR REPLACE FUNCTION cpres.rerank_distance(query text, content text)
 RETURNS real
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE STRICT SECURITY DEFINER
BEGIN ATOMIC
 SELECT
         CASE
             WHEN (content ~~* (('%'::text || query) || '%'::text)) THEN '-1'::integer
             ELSE 1
         END AS "case";
END;

