 RETURNS text
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE SECURITY DEFINER
 SET search_path TO 'cpres', 'pg_catalog'
BEGIN ATOMIC
 WITH t(text) AS (
          SELECT translation.text
            FROM cpres.translation
